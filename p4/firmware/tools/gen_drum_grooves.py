#!/usr/bin/env python3
"""Generates components/nano_audio/drum_grooves.c: the grooves of the Duo DAW (DuoKit/Sources/DuoKit/DrumLoops.swift
in the Iphone-Duo-DAW-und-Plugins project beside this one) for the board's drum machine, names in English.

Run from firmware/:  python3 tools/gen_drum_grooves.py
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = None
for folder in ROOT.parents:
    p = folder / 'Iphone-Duo-DAW-und-Plugins' / 'app' / 'DuoKit' / 'Sources' / 'DuoKit' / 'DrumLoops.swift'
    if p.is_file():
        SRC = p
        break
if not SRC:
    sys.exit('DrumLoops.swift of the Duo DAW not found beside this project')

ROLES = {'kick': 'DRUM_KICK', 'snare': 'DRUM_SNARE', 'clap': 'DRUM_CLAP', 'closedHat': 'DRUM_HAT', 'openHat': 'DRUM_OPENHAT',
         'lowTom': 'DRUM_LOWTOM', 'highTom': 'DRUM_HIGHTOM', 'ride': 'DRUM_RIDE', 'crash': 'DRUM_CRASH'}
ORDER = ['DRUM_KICK', 'DRUM_SNARE', 'DRUM_CLAP', 'DRUM_HAT', 'DRUM_OPENHAT', 'DRUM_LOWTOM', 'DRUM_HIGHTOM', 'DRUM_RIDE', 'DRUM_CRASH']
STYLES = {'Gerade': 'Straight', 'Ruhig': 'Calm', 'Groove': 'Groove', 'Tanz': 'Dance', 'Latin': 'Latin', 'Funk': 'Funk',
          'Alternative': 'Alternative'}
WORDS = [('8tel', '8ths'), ('16tel', '16ths'), ('offen', 'open'), ('Takte', 'bars'), ('Ballade', 'Ballad'),
         ('Triolen', 'Triplet'), ('Akzente', 'accents'), ('Gerade', 'Straight'), ('runter', 'down'),
         ('Einsatz Crash', 'Crash entry'), ('Stopp', 'Stop')]

text = SRC.read_text()
body = text[text.index('public static let all'):text.index('static func loop')]
loops = []
for m in re.finditer(r'loop\("([^"]+)",\s*"([^"]+)",\s*\[(.*?)\]\s*(,[^)]*)?\)', body, re.S):
    name, style, lanes, extra = m.group(1), m.group(2), m.group(3), m.group(4) or ''
    lane = {ROLES[r]: s for r, s in re.findall(r'DrumRole\.(\w+):\s*"([^"]*)"', lanes)}
    swing = float(re.search(r'swing:\s*([\d.]+)', extra).group(1)) if 'swing' in extra else 0.0
    spb = int(re.search(r'stepsPerBar:\s*(\d+)', extra).group(1)) if 'stepsPerBar' in extra else 16
    steps = max(len(s) for s in lane.values())
    for w, e in WORDS:
        name = name.replace(w, e)
    if name.startswith('Stil '):   # after a drummer: "Stubblefield style"
        name = name[5:] + ' style'
    loops.append((name.strip(), STYLES.get(style, style), spb, max(1, steps // spb), swing, lane))
if not loops:
    sys.exit('no grooves found')

out = ['// Generated by tools/gen_drum_grooves.py from the Duo DAW\'s DuoKit/DrumLoops.swift - do not edit.',
       '#include "drum_machine.h"', '', 'const drum_groove_t DRUM_GROOVES[] = {']
for name, style, spb, bars, swing, lane in loops:
    lanes = ', '.join('[%s] = "%s"' % (k, lane[k]) for k in ORDER if k in lane)
    out.append('    { "%s", "%s", %d, %d, %.2ff, { %s } },' % (name, style, spb, bars, swing, lanes))
out += ['};', 'const int DRUM_GROOVE_COUNT = sizeof(DRUM_GROOVES) / sizeof(DRUM_GROOVES[0]);', '']
(ROOT / 'components' / 'nano_audio' / 'drum_grooves.c').write_text('\n'.join(out))
print('components/nano_audio/drum_grooves.c: %d grooves (%s)' % (len(loops), ', '.join(sorted({l[1] for l in loops}))))
