#!/usr/bin/env python3
"""Generates main/private/fx_neural_private.c: a third group of sounds for the FX editor's info page, for the own build.

The group holds Neural DSP's factory effect presets as they were read off a Quad Cortex, for the Nano Cortex models
whose every control is the same on both devices. They are Neural DSP's, so they are private like the pedal pictures:
the data (main/private/neural_presets.json) and the generated file stay in main/private, which git ignores; the
published firmware is built with main/fx_neural.c, which has none.

main/private/neural_presets.json: { "models": { "<model type>": { "name", "default": [[control index, 0-1], ...] or
null, "presets": [ { "name", "bass": bool, "values": [[control index, 0-1], ...] } ] } } } - every control of the
model, as the Nano's own 0-1. The line under a preset's name lists only the controls that differ from the model's
default (up to SHOWN of them), in the editor's units; Apply sets all of them.

Run from the project folder:  python3 tools/gen_neural.py   (does nothing when there is no private data)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MODELS = {m[0]: m for m in json.loads((ROOT / 'tools' / 'editor_models.json').read_text())['models']}
SOURCE = ROOT / 'main' / 'private' / 'neural_presets.json'
OUT = ROOT / 'main' / 'private' / 'fx_neural_private.c'
SHOWN = 5          # controls named under a preset
MAX_PRESETS = 28   # per model (INFO_MAX_SOUNDS in main/ui.c leaves room for these beside the other two groups)


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', ' ') + '"'


def shown(param, n):
    """A control's value as the editor writes it, from the Nano's 0-1."""
    if param[1] == 'e':
        options = param[2]
        return options[round(n * (len(options) - 1))] if options else ''
    low, high, step, unit, decimals = param[2], param[3], param[4], param[5], int(param[6])
    skew = float(param[7]) if len(param) > 7 else 1.0
    value = low + (high - low) * (n ** (1.0 / skew))
    if step:
        value = round(value / step) * step
    text = '%.*f' % (decimals, value)
    return text + (' ' + unit if unit else '')


def main():
    if not SOURCE.is_file():
        print('No main/private/neural_presets.json - nothing to do (the published build has no such presets)')
        return
    data = json.loads(SOURCE.read_text())['models']
    parts = ['// Generated by tools/gen_neural.py from main/private/neural_presets.json - do not edit. PRIVATE: Neural DSP\'s',
             '// factory effect presets as read off a Quad Cortex - never publish (main/private is ignored by git).',
             '#include "fx_neural.h"', '#include <stddef.h>', '']
    entries, total = [], 0
    for key in sorted(data, key=int):
        mtype, entry = int(key), data[key]
        if mtype not in MODELS:
            sys.exit('%s (%d) is not in the model table' % (entry['name'], mtype))
        params = MODELS[mtype][4]
        default = dict(map(tuple, entry['default'])) if entry.get('default') else {}
        rows = []
        for n, preset in enumerate(entry['presets'][:MAX_PRESETS]):
            values = preset['values']
            if any(i >= len(params) for i, _ in values):
                sys.exit('%s "%s": a control the model table does not have' % (entry['name'], preset['name']))
            differing = [(i, v) for i, v in values if i not in default or shown(params[i], v) != shown(params[i], default[i])]
            texts = ['%s %s' % (params[i][0], shown(params[i], v)) for i, v in differing[:SHOWN]]
            if len(differing) > SHOWN:
                texts.append('\u2026')
            line = ' \u00b7 '.join(texts) if texts else 'As the model starts'
            parts.append('static const nano_focus_value_t n%d_%d[] = { %s };' % (mtype, n, ', '.join('{ %d, %.4ff }' % (i, v) for i, v in values)))
            rows.append('    { %s, %s, "", %d, n%d_%d },' % (c_str(preset['name']), c_str(line), len(values), mtype, n))
        parts.append('static const nano_info_sound_t n%d[] = {' % mtype)
        parts += rows
        parts += ['};', '']
        entries.append('    { %d, %d, n%d },' % (mtype, len(rows), mtype))
        total += len(rows)
    parts += ['static const struct { uint32_t type; int count; const nano_info_sound_t *sounds; } NEURAL[] = {'] + entries + ['};', '',
              'const nano_info_sound_t *nano_fx_neural(uint32_t type, int *count)', '{',
              '    for (size_t i = 0; i < sizeof(NEURAL) / sizeof(NEURAL[0]); i++) {',
              '        if (NEURAL[i].type != type) continue;',
              '        *count = NEURAL[i].count;',
              '        return NEURAL[i].sounds;',
              '    }',
              '    *count = 0;',
              '    return NULL;', '}', '']
    OUT.write_text('\n'.join(parts))
    print('main/private/fx_neural_private.c: %d presets for %d models' % (total, len(entries)))
    write_editor(data)


def number(param, n):
    """A control's value for the editor: the number in its unit, or a list's label."""
    if param[1] == 'e':
        return param[2][round(n * (len(param[2]) - 1))]
    low, high, step = param[2], param[3], param[4]
    skew = float(param[7]) if len(param) > 7 else 1.0
    value = low + (high - low) * (n ** (1.0 / skew))
    if step:
        value = round(value / step) * step
    return round(value, 4)


def write_editor(data):
    """The same presets for the Nano Cortex Editor's effect info, into its private img/ (if the editor is next to
    this project and has that folder): img/neural-presets.js sets window.NEURAL_FX_PRESETS by model name."""
    editor = next((f / 'nano-cortex-editor' for f in ROOT.parents if (f / 'nano-cortex-editor' / 'img').is_dir()), None)
    if not editor:
        print('No nano-cortex-editor/img beside this project - the editor gets no file')
        return
    out = {}
    for key in sorted(data, key=int):
        mtype, entry = int(key), data[key]
        params = MODELS[mtype][4]
        default = dict(map(tuple, entry['default'])) if entry.get('default') else {}
        rows = []
        for preset in entry['presets'][:MAX_PRESETS]:
            values = {params[i][0]: number(params[i], v) for i, v in preset['values']}
            differing = [params[i][0] for i, v in preset['values'] if i not in default or shown(params[i], v) != shown(params[i], default[i])]
            rows.append({'name': preset['name'], 'values': values, 'show': differing[:SHOWN]})
        out[MODELS[mtype][1]] = rows
    text = ('// Generated by nano-cortex-controller/tools/gen_neural.py - do not edit. PRIVATE (img/ is not published):\n'
            '// Neural DSP\'s factory effect presets as read off a Quad Cortex, for the models whose controls are the same.\n'
            'window.NEURAL_FX_PRESETS = ' + json.dumps(out, ensure_ascii=False) + ';\n')
    (editor / 'img' / 'neural-presets.js').write_text(text)
    print('%s: %d models' % (editor / 'img' / 'neural-presets.js', len(out)))


if __name__ == '__main__':
    main()
